_TEMPLATES = {
    "generic": _note_generic,
    "polite": _note_polite,
    "press": _note_press,
}


class Cipher(BaseCipher):
    """Extortion-note generator (social-engineering pattern simulation)."""

    name = "Ransom Note"
    command = "rn"
    help_menu = HELP
    binary = True  # reads fe-encrypted files itself; owns its -o output

    # ------------------------------------------------------------------ encode

    def encode(self, args: object) -> CipherResult:
        template = (getattr(args, "template", None) or "generic").lower()
        if template not in _TEMPLATES:
            valid = ", ".join(TEMPLATES)
            return CipherResult(f"Unknown template '{template}'. Choose: {valid}", False)

        hours = getattr(args, "deadline", None) or DEFAULT_HOURS
        try:
            hours = int(hours)
        except (TypeError, ValueError):
            return CipherResult("Deadline must be a whole number of hours", False)
        if hours < 1:
            return CipherResult("Deadline must be at least 1 hour", False)

        key = getattr(args, "key", None)
        fingerprint = _fingerprint(key) if key else None

        victim = getattr(args, "text", None)
        if not victim:
            victim = self._victim_from_file(getattr(args, "file", None))
        if not victim:
            victim = _random_victim_id()

        note = _TEMPLATES[template](victim, fingerprint, _deadline(hours), hours)

        output = getattr(args, "output", None)
        if output:
            try:
                Path(output).write_text(note, encoding="utf-8")
            except OSError as exc:
                return CipherResult(f"Could not write note: {exc}", False)
            return CipherResult(f"Ransom note written to {output}", True)
        return CipherResult(note, True)

    def brute(self, args: object) -> CipherResult:
        return CipherResult("Ransom note generation does not support brute force", False)

    # --------------------------------------------------------------- internals

    @staticmethod
    def _victim_from_file(file_path: str | None) -> str | None:
        """Derive the victim ID from the salt of an fe-encrypted file."""
        if not file_path:
            return None
        try:
            blob = Path(file_path).read_bytes()
        except OSError:
            return None
        if not blob.startswith(MAGIC) or len(blob) < SALT_OFFSET + SALT_SIZE:
            return None
        salt = blob[SALT_OFFSET : SALT_OFFSET + SALT_SIZE]
        return _victim_id_from_salt(salt)
